#!/usr/bin/env bash
#
# Logbase — Docker lifecycle. This is the deployment where inbound UDP works
# end to end, unlike single-port PaaS hosts.
#
#   ./scripts/docker.sh up        build and start (detached)
#   ./scripts/docker.sh down      stop and remove
#   ./scripts/docker.sh logs      follow container output
#   ./scripts/docker.sh build     build the image only
#   ./scripts/docker.sh status    show container and port state
#   ./scripts/docker.sh --help
#
# docker-compose.yml requires JWT_SECRET and TURSO_DATABASE_URL. If a .env.docker
# file exists it is used; otherwise one is generated pointing at a container-local
# SQLite file.
#
set -euo pipefail
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/common.sh"
cd "$ROOT"

DOCKER_ENV="$ROOT/.env.docker"

CMD="${1:-}"
[ $# -gt 0 ] && shift || true

# Validate the sub-command before touching Docker, so a typo reports the typo
# rather than "Docker is not installed".
case "$CMD" in
  --help|-h|"") sed -n '2,15p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
  build|up|down|logs|status) ;;
  *) die "Unknown command: $CMD  (try --help)" ;;
esac

header "docker"

has_cmd docker || die "Docker is not installed — https://docs.docker.com/get-docker/"
docker info >/dev/null 2>&1 || die "Docker daemon is not running — start Docker Desktop and retry"

# `docker compose` (v2) with a fallback to the legacy `docker-compose` binary.
if docker compose version >/dev/null 2>&1; then
  DC="docker compose"
elif has_cmd docker-compose; then
  DC="docker-compose"
else
  die "Neither 'docker compose' nor 'docker-compose' is available"
fi

ensure_docker_env() {
  if [ -f "$DOCKER_ENV" ]; then
    ok "Using existing .env.docker"
    return
  fi
  info "Creating .env.docker…"
  cat > "$DOCKER_ENV" <<EOF
# Docker environment — generated by scripts/docker.sh. Git-ignored.
# Read automatically by docker compose via --env-file.

JWT_SECRET=$(gen_secret)
JWT_EXPIRES_IN=7d
LOG_RETENTION_HOURS=24

# Container-local SQLite file. Point this at libsql://… to use cloud Turso.
TURSO_DATABASE_URL=file:./data/logbase.db
TURSO_AUTH_TOKEN=

INGEST_BODY_LIMIT=10mb
MAX_BATCH_SIZE=1000
PUBLIC_INGEST_HOST=localhost

UDP_ENABLED=true
UDP_BIND_HOST=0.0.0.0
UDP_PORT_RANGE=10000-10010
UDP_MAX_LISTENERS=1
UDP_MAX_PACKET_BYTES=65507
UDP_QUEUE_SIZE=5000
EOF
  ok "Created .env.docker (fresh JWT_SECRET generated)"
}

case "$CMD" in
  build)
    section "Build"
    $DC build "$@"
    ok "Image built"
    ;;

  up)
    ensure_docker_env
    section "Start"
    require_free_tcp_port 3000 "a different host port in docker-compose.yml"
    $DC --env-file "$DOCKER_ENV" up -d --build "$@"

    if wait_for_http "http://localhost:3000/healthz" 60; then
      ok "Container healthy"
      printf '\n'
      printf '  %s  %s\n' "Dashboard" "${C}http://localhost:3000${N}"
      printf '  %s  %s\n' "UDP ports" "${DIM}10000-10010/udp (published to the host)${N}"
      printf '\n'
      info "Send a test datagram once a UDP collector exists on port 10000:"
      printf '    %s\n' "${DIM}printf '%s\\\\n' '{\"level\":\"info\",\"app\":\"svc\",\"message\":\"hi\"}' | nc -u -w1 127.0.0.1 10000${N}"
      printf '\n'
      info "Follow output:  ./scripts/docker.sh logs"
    else
      err "Container did not become healthy within 60s:"
      $DC logs --tail 40
      exit 1
    fi
    ;;

  down)
    section "Stop"
    $DC down "$@"
    ok "Containers removed"
    ;;

  logs)
    $DC logs -f --tail 100 "$@"
    ;;

  status)
    section "Containers"
    $DC ps
    section "Health"
    if curl -sf http://localhost:3000/healthz 2>/dev/null; then
      printf '\n'
    else
      warn "Health endpoint not responding on :3000"
    fi
    ;;
esac
