#!/usr/bin/env bash
#
# Logbase — first-time setup.
#
#   ./scripts/setup.sh            prepare a local development environment
#   ./scripts/setup.sh --force    regenerate .env.local (new JWT_SECRET)
#   ./scripts/setup.sh --help
#
# Verifies the toolchain, installs dependencies and generates a git-ignored
# .env.local pointing at a local SQLite file. Safe to re-run.
#
set -euo pipefail
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/common.sh"
cd "$ROOT"

LOCAL_ENV="$ROOT/.env.local"
FORCE=0

while [ $# -gt 0 ]; do
  case "$1" in
    --force) FORCE=1; shift ;;
    --help|-h) sed -n '2,10p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "Unknown option: $1  (try --help)" ;;
  esac
done

header "setup"

# ── 1. Toolchain ──────────────────────────────────────────────────────────────
section "Toolchain"
require_node
has_cmd npm  || die "npm is not installed (it ships with Node.js)"
ok "npm $(npm -v)"
has_cmd git  && ok "git $(git --version | awk '{print $3}')" || warn "git not found (optional)"
has_cmd curl && ok "curl available"                          || warn "curl not found — scripts/test.sh needs it"
has_cmd lsof && ok "lsof available"                          || warn "lsof not found — port checks will be skipped"

# ── 2. Dependencies ───────────────────────────────────────────────────────────
section "Dependencies"
ensure_deps

# ── 3. Local environment ──────────────────────────────────────────────────────
section "Environment"
mkdir -p "$ROOT/data"
ok "data/ directory ready"

if [ -f "$LOCAL_ENV" ] && [ "$FORCE" -eq 0 ]; then
  ok ".env.local already exists (use --force to regenerate)"
else
  [ -f "$LOCAL_ENV" ] && warn "Overwriting .env.local — existing sessions will be invalidated"

  cat > "$LOCAL_ENV" <<EOF
# Local development overrides — generated by scripts/setup.sh
#
# Git-ignored. Exported by the dev scripts BEFORE src/server.js reads .env.
# dotenv never overwrites a variable that is already set, so these values win
# over .env — which is what keeps local runs off the cloud database.

PORT=3000
JWT_SECRET=$(gen_secret)
JWT_EXPIRES_IN=7d
LOG_RETENTION_HOURS=24

OAUTH_ACCESS_TOKEN_TTL=3600
OAUTH_REFRESH_TOKEN_TTL=2592000

# Local SQLite file — keeps development off the production database.
DB_ADAPTER=libsql
TURSO_DATABASE_URL=file:./data/local.db
TURSO_AUTH_TOKEN=

# Ingestion
INGEST_BODY_LIMIT=10mb
MAX_BATCH_SIZE=1000

# UDP listener — fully functional on localhost.
UDP_ENABLED=true
UDP_BIND_HOST=0.0.0.0
UDP_PORT_RANGE=10000-10010
UDP_MAX_LISTENERS=1
UDP_MAX_PACKET_BYTES=65507
UDP_QUEUE_SIZE=5000
EOF
  ok "Created .env.local (fresh JWT_SECRET generated)"
fi

# ── 4. Production .env awareness ──────────────────────────────────────────────
if [ -f "$ROOT/.env" ]; then
  # shellcheck disable=SC2016
  PROD_URL="$(grep -E '^TURSO_DATABASE_URL=' "$ROOT/.env" | head -1 | cut -d= -f2- || true)"
  if is_cloud_db "$PROD_URL"; then
    warn ".env points at a CLOUD database — the dev scripts will not touch it."
    info "To target it deliberately:  ./scripts/dev.sh --turso"
  fi
fi

# ── 5. Verify the schema compiles ─────────────────────────────────────────────
section "Verification"
if node -e "
  const Adapter = require('./src/db/adapters/libsql');
  const a = Object.create(Adapter.prototype);
  a.compileSchema(require('./src/db/schema/tables.json'),
                  require('./src/db/schema/indexes.json'));
" 2>/dev/null; then
  ok "Database schema compiles"
else
  die "Schema failed to compile — run ./scripts/check.sh for details"
fi

printf '\n'
ok "${B}Setup complete${N}"
printf '\n'
printf '  %s  %s\n' "Start the app " "${C}npm run dev${N}"
printf '  %s  %s\n' "Run the checks" "${DIM}npm run check${N}"
printf '  %s  %s\n' "Run the tests " "${DIM}npm test${N}"
printf '\n'
